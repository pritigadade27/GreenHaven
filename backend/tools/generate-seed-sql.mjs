import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const FRONTEND = resolve(here, '..', '..', 'frontend', 'src', 'data');
const OUT = resolve(here, '..', 'db', 'data.sql');

const moduleCache = new Map();

async function moduleUri(file) {
  if (moduleCache.has(file)) return moduleCache.get(file);

  let src = readFileSync(join(FRONTEND, file), 'utf8');

  src = src.replace(
    /import\s+(\w+)\s+from\s+'[^']*\/images\/([\w-]+)\/([\w-]+\.(?:jpg|jpeg|png|webp))';/g,
    (_m, ident, dir, filename) => `const ${ident} = '${dir}/${filename}';`
  );

  src = src.replace(
    /new URL\(`\.\.\/assets\/images\/([\w-]+)\/\$\{(\w+)\}\.(\w+)`,\s*import\.meta\.url\)\.href/g,
    (_m, dir, ident, ext) => `\`${dir}/\${${ident}}.${ext}\``
  );

  const siblings = [...src.matchAll(/from\s+'\.\/([\w.-]+)'/g)].map((m) => m[1]);
  for (const name of new Set(siblings)) {
    const uri = await moduleUri(name.endsWith('.js') ? name : `${name}.js`);
    src = src.split(`'./${name}'`).join(`'${uri}'`);
  }

  const uri = 'data:text/javascript;base64,' + Buffer.from(src, 'utf8').toString('base64');
  moduleCache.set(file, uri);
  return uri;
}

const loadDataModule = async (file) => import(await moduleUri(file));

const q = (v) =>
  v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`;
const bool = (v) => (v ? 'TRUE' : 'FALSE');

const { PLANTS, CATEGORIES } = await loadDataModule('plants.js');
const { BADGES } = await loadDataModule('badges.js');
const { EXTRA_PLANTS } = await loadDataModule('plants-extra.js');
const { MERCHANDISE } = await loadDataModule('merchandise.js');

const CATALOGUE = [...PLANTS, ...EXTRA_PLANTS, ...MERCHANDISE];

const codes = new Set();
for (const item of CATALOGUE) {
  if (codes.has(item.id)) throw new Error(`duplicate product code: ${item.id}`);
  codes.add(item.id);
  if (!CATEGORIES.some((c) => c.slug === item.category)) {
    throw new Error(`${item.id} (${item.slug}) is in unknown category '${item.category}'`);
  }
}

const lines = [];
lines.push('-- ===========================================================================');
lines.push('--  Green Haven — seed data');
lines.push('--  GENERATED by backend/tools/generate-seed-sql.mjs from');
lines.push('--  frontend/src/data/plants.js — do not edit by hand, regenerate instead.');
lines.push('-- ===========================================================================');
lines.push('');
lines.push('SET NAMES utf8mb4;');
lines.push('');

lines.push('-- categories -------------------------------------------------------------');
lines.push('INSERT INTO category (slug, name, blurb, sort_order) VALUES');
lines.push(
  CATEGORIES.map((c, i) => `  (${q(c.slug)}, ${q(c.name)}, ${q(c.blurb)}, ${i + 1})`).join(',\n') + ';'
);
lines.push('');

lines.push('-- badges -----------------------------------------------------------------');
lines.push('INSERT INTO badge (code, label, tone, icon, detail) VALUES');
lines.push(
  Object.entries(BADGES)
    .map(([code, b]) => `  (${q(code)}, ${q(b.label)}, ${q(b.tone)}, ${q(b.icon)}, ${q(b.detail)})`)
    .join(',\n') + ';'
);
lines.push('');

lines.push('-- plants -----------------------------------------------------------------');
for (const p of CATALOGUE) {
  const c = p.care ?? {};
  lines.push(
    `INSERT INTO plant (code, slug, name, botanical_name, category_id, price, mrp, stock, image,\n` +
      `  rating, review_count, short_description, description, care_tip,\n` +
      `  pet_safety, difficulty, light_need, water_need, maintenance, growth_rate, mature_size,\n` +
      `  care_light, care_water, care_soil, care_humidity, care_temperature, care_feed, care_repot,\n` +
      `  is_featured, is_best_seller)\n` +
      `SELECT ${q(p.id)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.botanical)}, c.id,\n` +
      `  ${p.price}, ${p.mrp ?? 'NULL'}, ${p.stock ?? 0}, ${q(p.image)},\n` +
      `  ${p.rating ?? 0}, ${p.reviews ?? 0}, ${q(p.short)}, ${q(p.description)}, ${q(p.tip)},\n` +
      `  ${q(p.petSafety)}, ${q(p.difficulty)}, ${q(p.light)}, ${q(p.water)},\n` +
      `  ${q(p.maintenance)}, ${q(p.growth)}, ${q(p.size)},\n` +
      `  ${q(c.light)}, ${q(c.water)}, ${q(c.soil)}, ${q(c.humidity)},\n` +
      `  ${q(c.temperature)}, ${q(c.feed)}, ${q(c.repot)},\n` +
      `  ${bool(p.featured)}, ${bool(p.bestSeller)}\n` +
      `FROM category c WHERE c.slug = ${q(p.category)};`
  );
}
lines.push('');

lines.push('-- badge assignments ------------------------------------------------------');
for (const p of CATALOGUE) {
  for (const badge of p.badges ?? []) {
    lines.push(
      `INSERT INTO plant_badge (plant_id, badge_id) ` +
        `SELECT p.id, b.id FROM plant p, badge b ` +
        `WHERE p.code = ${q(p.id)} AND b.code = ${q(badge)};`
    );
  }
}
lines.push('');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n') + '\n', 'utf8');

const badgeCount = CATALOGUE.reduce((n, p) => n + (p.badges?.length ?? 0), 0);
const merch = CATALOGUE.filter((p) => p.isMerchandise).length;
console.log(`data.sql written -> ${OUT}`);
console.log(
  `  ${CATEGORIES.length} categories, ${Object.keys(BADGES).length} badges, ` +
    `${CATALOGUE.length} products (${CATALOGUE.length - merch} plants, ${merch} merchandise), ` +
    `${badgeCount} badge assignments`
);
